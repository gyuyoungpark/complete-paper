#!/usr/bin/env python3
"""Device schematics drawn by code, in one fixed projection, on a matplotlib Axes.

A schematic built here is vector art that sits in the same figure as the data panels, so it
shares their fonts, their colours and their alignment, and it can be regenerated when the
device changes. Nothing is generated by an image model.

    import schematic3d as s3
    sc = s3.Scene(azim=-58, elev=24)                        # one view for every schematic of the paper
    sc.box((0, 0, 0), (10, 6, 1.0), "#D9D9D9")              # substrate: origin, size, colour
    sc.box((1, 2, 1.0), (8, 2, 0.5), "#D55E00", label="Mn3Sn")
    sc.cylinder((5, 3, 1.5), 0.6, 0.8, "#999999")           # a pillar: centre of base, radius, height
    sc.stack((12, 0, 0), (3, 3), [(1.0, "#D9D9D9", "substrate"), (0.4, "#8C8C8C", "W"), (0.6, "#D55E00", "Mn3Sn")])
    sc.prism(s3.hall_bar(8, 1, arms=(2.5, 5.5), arm_length=1.5, arm_width=0.6, origin=(1, 3)), 1.0, 0.3, "#D55E00")
    sc.arrow((1.5, 3, 1.9), (8.5, 3, 1.9), label=r"$j$")
    sc.note(r"Mn$_3$Sn", at=(7, 2, 1.5), offset=(14, -16))  # text with a leader line
    sc.triad((-1.0, -3.0, 0), 1.5)                          # in a free corner, outside the device
    sc.draw(ax)

Projection. Parallel (axonometric) by default: edges that are parallel in the device stay
parallel on the page, vertical edges stay vertical, and equal lengths along one axis stay
equal. `perspective=d` puts the eye at distance d (in scene units) for a mild convergence;
keep d several times the size of the device. Use one projection and one pair of angles for
every schematic of a paper. `Scene(azim=-90, elev=0)` is a flat side view, the usual drawing
of a layer stack in cross-section; `Scene(azim=-90, elev=90)` is a top view. Flat views are
drawn without shading.

Shading. Flat tones only: the top face is the lightest, faces turned to the left of the page
carry the base colour, faces turned to the right are darker. That is one light, from the
upper left, for every object.

Solids are boxes, upright cylinders (round or elliptical) and prisms: flat parts with any
outline, such as a Hall bar or an L-shaped wire. Solids must not interpenetrate: draw a part
that is not convex as one prism, not as boxes that run through each other. Curved surfaces
other than cylinders, cut-away views and transparent solids are outside what this module draws.
Needs matplotlib and numpy.
"""
import math

import numpy as np
from matplotlib.colors import to_rgb
from matplotlib.patches import FancyArrowPatch, Polygon

TOP, LEFT, RIGHT, UNDER = 0.32, 0.0, -0.20, -0.35      # mix towards white (+) or black (-)


def hall_bar(length, width, arms=(), arm_length=1.0, arm_width=0.5, origin=(0.0, 0.0)):
    """Outline of a bar along x with pairs of side arms at the positions `arms`: pass it to Scene.prism().

    origin is the lower-left corner of the bar itself; the arms reach arm_length beyond both long edges.
    """
    x0, y0 = origin
    pts = [(x0, y0)]
    for a in sorted(arms):
        pts += [(x0 + a - arm_width / 2, y0), (x0 + a - arm_width / 2, y0 - arm_length),
                (x0 + a + arm_width / 2, y0 - arm_length), (x0 + a + arm_width / 2, y0)]
    pts += [(x0 + length, y0), (x0 + length, y0 + width)]
    for a in sorted(arms, reverse=True):
        pts += [(x0 + a + arm_width / 2, y0 + width), (x0 + a + arm_width / 2, y0 + width + arm_length),
                (x0 + a - arm_width / 2, y0 + width + arm_length), (x0 + a - arm_width / 2, y0 + width)]
    pts.append((x0, y0 + width))
    return pts


def tone(colour, f):
    c = np.array(to_rgb(colour))
    return tuple(c + (1 - c) * f) if f >= 0 else tuple(c * (1 + f))


class Scene:
    def __init__(self, azim=-58, elev=24, perspective=None, edge="#262626", edge_width=0.5):
        a, e = math.radians(azim), math.radians(elev)
        self.c = np.array([math.cos(e) * math.cos(a), math.cos(e) * math.sin(a), math.sin(e)])   # towards the eye
        self.r = np.array([-math.sin(a), math.cos(a), 0.0])                                      # page right
        self.u = np.array([-math.sin(e) * math.cos(a), -math.sin(e) * math.sin(a), math.cos(e)])  # page up
        self.perspective, self.edge, self.lw = perspective, edge, edge_width
        self.solids, self.arrows, self.notes, self.overlays = [], [], [], []
        self.centre = None

    # ----- geometry -----
    def project(self, p):
        """World point(s) (x, y, z) to page coordinates; z is up."""
        p = np.atleast_2d(np.asarray(p, float))
        q = p - (self.centre if self.centre is not None else 0)
        xy = np.stack([q @ self.r, q @ self.u], axis=1)
        if self.perspective:
            xy = xy * (self.perspective / (self.perspective - q @ self.c))[:, None]
        return xy

    def _facing(self, normal, at):
        if self.perspective:
            eye = (self.centre if self.centre is not None else 0) + self.perspective * self.c
            return float(np.dot(normal, eye - at)) > 1e-9
        return float(np.dot(normal, self.c)) > 1e-9

    def _side_tone(self, normal):
        if abs(self.c[2]) < 1e-9 or abs(self.c[2]) > 1 - 1e-9:
            return 0.0                                       # a pure side view or top view is a flat drawing: no shading
        if normal[2] > 0.5:
            return TOP
        if normal[2] < -0.5:
            return UNDER
        t = (float(np.dot(normal, self.r)) + 1) / 2          # 0: turned left on the page, 1: turned right
        return LEFT + (RIGHT - LEFT) * t

    # ----- content -----
    def box(self, origin, size, colour, label=None):
        """A box with one corner at origin (x, y, z) and edge lengths size (dx, dy, dz)."""
        o, s = np.asarray(origin, float), np.asarray(size, float)
        self.solids.append({"kind": "box", "lo": o, "hi": o + s, "colour": colour, "label": label})
        return self

    def stack(self, origin, footprint, layers):
        """Layers of one footprint (dx, dy) piled up from origin: layers = [(thickness, colour, label), ...], bottom first."""
        x, y, z = origin
        for thickness, colour, *label in layers:
            self.box((x, y, z), (footprint[0], footprint[1], thickness), colour, label=label[0] if label else None)
            z += thickness
        return self

    def prism(self, outline, z, height, colour, label=None):
        """A flat part with any outline: corners (x, y) in order, extruded from z to z + height.

        One prism has one outline and no seams, so use it for a cross, a Hall bar, an L-shaped wire or a wedge."""
        xy = np.asarray(outline, float)
        x, y = xy[:, 0], xy[:, 1]
        if np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y) < 0:      # make it counter-clockwise: outward normals follow
            xy = xy[::-1]
        self.solids.append({"kind": "prism", "xy": xy, "z0": float(z), "h": float(height), "colour": colour, "label": label,
                            "lo": np.array([xy[:, 0].min(), xy[:, 1].min(), z], float),
                            "hi": np.array([xy[:, 0].max(), xy[:, 1].max(), z + height], float)})
        return self

    def cylinder(self, centre, radius, height, colour, label=None, radius_y=None, n=72):
        """An upright cylinder; centre is the middle of its base. radius_y makes it elliptical."""
        c = np.asarray(centre, float)
        rx, ry = float(radius), float(radius_y or radius)
        self.solids.append({"kind": "cyl", "c": c, "rx": rx, "ry": ry, "h": float(height), "n": n,
                            "lo": c - [rx, ry, 0], "hi": c + [rx, ry, height], "colour": colour, "label": label})
        return self

    def polygon(self, points, colour, alpha=0.75, label=None, outline=True):
        """A flat polygon through world points (a lattice plane, a cut, a domain wall). Drawn over the solids."""
        self.overlays.append({"kind": "poly", "pts": np.asarray(points, float), "colour": colour, "alpha": alpha,
                              "label": label, "outline": outline})
        return self

    def line(self, points, colour=None, width=None, style="-"):
        """A polyline through world points (a normal, an angle arc, a guide). Drawn over the solids."""
        self.overlays.append({"kind": "line", "pts": np.asarray(points, float), "colour": colour or self.edge,
                              "lw": width or self.lw, "style": style})
        return self

    def arc(self, centre, a, b, radius, colour=None, width=None, n=24):
        """The arc from direction a to direction b around centre: marks the angle between two directions."""
        a, b = np.asarray(a, float), np.asarray(b, float)
        a, b = a / np.linalg.norm(a), b / np.linalg.norm(b)
        ts = np.linspace(0, 1, n)
        dirs = [(1 - t) * a + t * b for t in ts]
        pts = [np.asarray(centre, float) + radius * d / np.linalg.norm(d) for d in dirs]
        return self.line(pts, colour, width)

    def arrow(self, start, end, colour="black", label=None, width=1.0, head=5.0, offset=(0, 5), behind=False, **text):
        """A straight arrow between two world points; label is written beside its middle."""
        self.arrows.append({"a": np.asarray(start, float), "b": np.asarray(end, float), "colour": colour,
                            "label": label, "lw": width, "head": head, "offset": offset, "behind": behind,
                            "text": text})
        return self

    def note(self, text, at, offset=(0, 0), leader=True, **kw):
        """Text tied to a world point: offset in points; a thin leader line when it is moved away."""
        self.notes.append({"text": text, "at": np.asarray(at, float), "offset": offset, "leader": leader, "kw": kw})
        return self

    def triad(self, origin, length, labels=(r"$x$", r"$y$", r"$z$"), colour="black", width=0.8):
        """Coordinate axes in the projection of the scene."""
        o = np.asarray(origin, float)
        for axis, name in zip(np.eye(3), labels):
            tip = o + axis * length
            step = self.project([o, tip])
            d = step[1] - step[0]
            d = d / (np.linalg.norm(d) or 1)
            self.arrow(o, tip, colour=colour, width=width, head=4.0, label=name, offset=tuple(5 * d), at_tip=True)
        return self

    # ----- drawing -----
    def _order(self):
        """Back-to-front order: a solid behind a plane that separates two solids is drawn first."""
        n = len(self.solids)
        before = [set() for _ in range(n)]              # before[j]: solids that must be drawn before j
        for i in range(n):
            for j in range(i + 1, n):
                a, b = self.solids[i], self.solids[j]
                first = None
                for k in (2, 0, 1):
                    if abs(self.c[k]) < 1e-9:
                        continue
                    if a["hi"][k] <= b["lo"][k] + 1e-9:
                        first = (i, j) if self.c[k] > 0 else (j, i)
                    elif b["hi"][k] <= a["lo"][k] + 1e-9:
                        first = (j, i) if self.c[k] > 0 else (i, j)
                    if first:
                        break
                if first is None:                        # touching or overlapping: fall back on depth
                    da = float(np.dot((a["lo"] + a["hi"]) / 2, self.c))
                    db = float(np.dot((b["lo"] + b["hi"]) / 2, self.c))
                    first = (i, j) if da <= db else (j, i)
                before[first[1]].add(first[0])
        order, done = [], set()
        while len(order) < n:
            ready = [k for k in range(n) if k not in done and before[k] <= done]
            if not ready:                                # a cycle: take the deepest of what is left
                ready = [min((k for k in range(n) if k not in done),
                             key=lambda k: float(np.dot((self.solids[k]["lo"] + self.solids[k]["hi"]) / 2, self.c)))]
            k = min(ready, key=lambda k: float(np.dot((self.solids[k]["lo"] + self.solids[k]["hi"]) / 2, self.c)))
            order.append(k)
            done.add(k)
        return order

    def _box_faces(self, s):
        lo, hi = s["lo"], s["hi"]
        x0, y0, z0 = lo
        x1, y1, z1 = hi
        faces = [((0, 0, 1), [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]),
                 ((0, 0, -1), [(x0, y0, z0), (x0, y1, z0), (x1, y1, z0), (x1, y0, z0)]),
                 ((1, 0, 0), [(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)]),
                 ((-1, 0, 0), [(x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0)]),
                 ((0, 1, 0), [(x0, y1, z0), (x0, y1, z1), (x1, y1, z1), (x1, y1, z0)]),
                 ((0, -1, 0), [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)])]
        for normal, pts in faces:
            normal, pts = np.array(normal, float), np.array(pts, float)
            if self._facing(normal, pts.mean(axis=0)):
                yield pts, tone(s["colour"], self._side_tone(normal)), True

    def _prism_faces(self, s):
        xy, z0, z1 = s["xy"], s["z0"], s["z0"] + s["h"]
        walls = []
        for a, b in zip(xy, np.roll(xy, -1, axis=0)):
            edge = b - a
            length = float(np.hypot(*edge))
            if length < 1e-12:
                continue
            normal = np.array([edge[1], -edge[0], 0.0]) / length
            quad = np.array([[a[0], a[1], z0], [b[0], b[1], z0], [b[0], b[1], z1], [a[0], a[1], z1]])
            if self._facing(normal, quad.mean(axis=0)):
                walls.append((float(np.dot(quad.mean(axis=0), self.c)), quad, normal))
        for _, quad, normal in sorted(walls, key=lambda w: w[0]):   # far walls first; a nearer wall may hide them
            yield quad, tone(s["colour"], self._side_tone(normal)), True
        up = self.c[2] >= 0                                          # seen from above: the top hides what lies behind it
        cap = np.column_stack([xy, np.full(len(xy), z1 if up else z0)])
        yield cap, tone(s["colour"], self._side_tone(np.array([0, 0, 1.0 if up else -1.0]))), True

    def _cyl_faces(self, s):
        c, rx, ry, h, n = s["c"], s["rx"], s["ry"], s["h"], s["n"]
        phi = np.linspace(0, 2 * math.pi, n + 1)
        ring = np.stack([c[0] + rx * np.cos(phi), c[1] + ry * np.sin(phi), np.full(n + 1, c[2])], axis=1)
        top = ring + [0, 0, h]
        visible = []
        for k in range(n):
            mid = (phi[k] + phi[k + 1]) / 2
            normal = np.array([math.cos(mid) / rx, math.sin(mid) / ry, 0.0])
            normal /= np.linalg.norm(normal)
            centre = (ring[k] + top[k + 1]) / 2
            if self._facing(normal, centre):
                visible.append(k)
                colour = tone(s["colour"], self._side_tone(normal))
                yield np.array([ring[k], ring[k + 1], top[k + 1], top[k]]), colour, False
        if visible:                                      # outline of the curved side
            ks = sorted(visible)
            breaks = [i for i in range(1, len(ks)) if ks[i] != ks[i - 1] + 1]
            if breaks:                                   # the visible arc wraps past phi = 0
                ks = ks[breaks[0]:] + ks[:breaks[0]]
            lower = [ring[k] for k in ks] + [ring[ks[-1] + 1]]
            upper = [top[k] for k in ks] + [top[ks[-1] + 1]]
            yield ("line", np.array([upper[0]] + lower + upper[::-1])), None, True      # a closed outline, also when no cap shows
        cap_normal = np.array([0, 0, 1.0])
        if self._facing(cap_normal, top.mean(axis=0)):
            yield top[:-1], tone(s["colour"], self._side_tone(cap_normal)), True
        elif self._facing(-cap_normal, ring.mean(axis=0)):
            yield ring[:-1], tone(s["colour"], self._side_tone(-cap_normal)), True

    def draw(self, ax, pad=0.04):
        """Draw the scene on ax: equal aspect, no axes, limits fitted to the content.

        The Axes keeps the box the layout gave it, so its panel label lines up with the other panels."""
        corners = [p for s in self.solids for p in (s["lo"], s["hi"])] + \
                  [p for a in self.arrows for p in (a["a"], a["b"])] + [m["at"] for m in self.notes] + \
                  [p for o in self.overlays for p in o["pts"]]
        self.centre = (np.min(corners, axis=0) + np.max(corners, axis=0)) / 2 if corners else np.zeros(3)
        seen, z = [], 2.0
        for a in self.arrows:
            if a["behind"]:
                seen.append(self._draw_arrow(ax, a, 1.5))
        for k in self._order():
            s = self.solids[k]
            faces = {"box": self._box_faces, "cyl": self._cyl_faces, "prism": self._prism_faces}[s["kind"]](s)
            labelled = False
            for pts, colour, outlined in faces:
                z += 0.01
                if isinstance(pts, tuple):               # an outline only
                    xy = self.project(pts[1])
                    ax.plot(xy[:, 0], xy[:, 1], color=self.edge, lw=self.lw, zorder=z, solid_joinstyle="round",
                            label="_outline")
                    seen.append(xy)
                    continue
                xy = self.project(pts)
                face = Polygon(xy, closed=True, facecolor=colour, zorder=z, joinstyle="round",
                               edgecolor=self.edge if outlined else colour, linewidth=self.lw if outlined else 0.3,
                               label=s["label"] if s["label"] and not labelled and outlined else "_face")
                face.base_colour = s["colour"]            # the colour the part stands for, before shading
                ax.add_patch(face)
                labelled = labelled or (bool(s["label"]) and outlined)
                seen.append(xy)
        for o in self.overlays:
            z += 0.01
            xy = self.project(o["pts"])
            if o["kind"] == "poly":
                face = Polygon(xy, closed=True, facecolor=o["colour"], alpha=o["alpha"], zorder=z, joinstyle="round",
                               edgecolor=self.edge if o["outline"] else "none", linewidth=self.lw,
                               label=o["label"] or "_plane")
                face.base_colour = o["colour"]
                ax.add_patch(face)
            else:
                ax.plot(xy[:, 0], xy[:, 1], color=o["colour"], lw=o["lw"], ls=o["style"], zorder=z, label="_guide",
                        solid_capstyle="round")
            seen.append(xy)
        for a in self.arrows:
            if not a["behind"]:
                seen.append(self._draw_arrow(ax, a, z + 1))
        for m in self.notes:
            xy = self.project(m["at"])[0]
            moved = m["leader"] and (abs(m["offset"][0]) + abs(m["offset"][1]) > 6)
            kw = dict(ha="center", va="center", color="black", zorder=z + 3, annotation_clip=False)
            kw.update(m["kw"])
            ax.annotate(m["text"], xy=xy, xytext=m["offset"], textcoords="offset points",
                        arrowprops=dict(arrowstyle="-", lw=self.lw, color=self.edge, shrinkA=1.5, shrinkB=0) if moved else None,
                        **kw)
            seen.append(xy[None, :])
        if seen:
            ax.update_datalim(np.concatenate(seen))
        ax.set_aspect("equal", adjustable="datalim")     # the panel keeps its place in the grid; the limits adapt
        ax.margins(pad)
        ax.autoscale_view()
        ax.axis("off")
        return ax

    def _draw_arrow(self, ax, a, z):
        xy = self.project([a["a"], a["b"]])
        ax.add_patch(FancyArrowPatch(xy[0], xy[1], arrowstyle=f"-|>,head_length={0.8 * a['head']:.1f},head_width={0.4 * a['head']:.1f}",
                                     mutation_scale=1.0, lw=a["lw"], color=a["colour"], shrinkA=0, shrinkB=0,
                                     zorder=z, label="_arrow"))
        if a["label"]:
            text = dict(a["text"])
            at = xy[1] if text.pop("at_tip", False) else xy.mean(axis=0)
            kw = dict(ha="center", va="center", color="black", zorder=z + 2, annotation_clip=False)
            kw.update(text)
            ax.annotate(a["label"], xy=at, xytext=a["offset"], textcoords="offset points", **kw)
        return xy


